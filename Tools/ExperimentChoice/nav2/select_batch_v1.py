"""Batch v1 for the offset-doorway Nav2 study (EXPLORATORY): supersedes batch v0 before any run.

Five v0 courses kept, five added where the two surrogate stand-in pairs disagree (learner/RESULTS.md,
"Which courses the real Nav2 batch should run first"). Writes courses_v1/, batch_v1.json, batch_v1.md.
Runs no simulator:
  ulimit -v 1500000; OPENBLAS_NUM_THREADS=1 nice -n 19 python3 -I Tools/ExperimentChoice/nav2/select_batch_v1.py
"""
from __future__ import annotations

import json
import os
import sys
from dataclasses import replace

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import course as C          # noqa: E402
import mechanics as M       # noqa: E402
import robots as R          # noqa: E402
from nav2.select_batch import FOOTPRINTS, T_WALL, W_DOOR  # noqa: E402

TRUTH = os.path.expanduser("~/.cache/expchoice/learner_truth_v1.jsonl")
# (d, e, origin). All wall edges are multiples of 5 cm; w = 0.90 m, t = 0.20 m as in v0.
COURSES = [(0.85, 0.70, "v0 #2"), (0.90, 0.70, "v0 #5"), (1.05, 0.70, "v0 #8"), (1.10, 0.70, "v0 #9"),
           (1.20, 0.70, "v0 #10"), (1.20, 0.45, "new"), (1.30, 0.65, "new"), (1.45, 0.85, "new"),
           (1.30, 0.45, "new"), (1.60, 0.20, "new")]
CANARY = (1.60, 0.20)          # the roomiest course
TIE_S = 1.0


def pair_cell(rows, pair, d_cm, e_cm):
    """Nearest pool cell (w = 0.90 m, catalog rectangle) of one stand-in pair, and what it says.
    Label: both fail if neither arm ever succeeds; tie if |mean J_A - J_B| < 1 s; else the faster arm."""
    cells = [r for r in rows if r["pair"] == pair and r["set"] == "pool" and r["w_cm"] == 90]
    best = min(cells, key=lambda r: (r["d_cm"] - d_cm) ** 2 + (r["e_cm"] - e_cm) ** 2)
    n = len(best["J_A"])
    ok_a, ok_b = best["status_A"].count("success"), best["status_B"].count("success")
    gap = sum(a - b for a, b in zip(best["J_A"], best["J_B"])) / n
    label = "both fail" if ok_a == 0 and ok_b == 0 else "tie" if abs(gap) < TIE_S else "B" if gap > 0 else "A"
    return {"cell_d_cm": best["d_cm"], "cell_e_cm": best["e_cm"], "success_A": "%d/%d" % (ok_a, n),
            "success_B": "%d/%d" % (ok_b, n), "mean_gap_s": round(gap, 1), "winner": label}


def main():
    base = R.load_robot("compact_diff")
    rows = [json.loads(line) for line in open(TRUTH, encoding="utf-8")]
    out_dir = os.path.join(HERE, "courses_v1")
    os.makedirs(out_dir, exist_ok=True)
    batch = []
    for d, e, origin in COURSES:
        crs = C.make_course(w=W_DOOR, e=e, d=d, t=T_WALL)
        box = C.ADMISSIBLE_BOX_V0
        in_box = (all(box[k][0] <= getattr(crs, k) <= box[k][1] for k in ("w_cm", "e_cm", "d_cm", "t_cm", "B_cm"))
                  and crs.e_cm + crs.w_cm / 2 <= crs.B_cm / 2 - box["side_clearance_cm"])
        with open(os.path.join(out_dir, "course_%s.json" % crs.course_id), "w", encoding="utf-8") as f:
            f.write(C.manifest_json(crs, base))
        entry = {"course_id": crs.course_id, "d_m": crs.d, "e_m": crs.e, "w_m": crs.w, "t_m": crs.t,
                 "origin": origin, "canary": (d, e) == CANARY, "in_admissible_box_v0": in_box, "footprints": {}}
        for name, (L, W) in FOOTPRINTS.items():
            rob = replace(base, L=L, W=W)
            cert = M.certificate(crs, rob)
            entry["footprints"][name] = {"L": L, "W": W, "two_rho": round(2 * M.rho(L, W), 4),
                                         "d_over_2rho": round(crs.d / (2 * M.rho(L, W)), 3),
                                         "regime": M.regime(crs.d, L, W), "certificate": cert["verdict"],
                                         "certificate_reason": cert["reason"],
                                         "four_flow_cycles": cert.get("four_flow_cycles")}
        entry["surrogate"] = {pair: pair_cell(rows, pair, crs.d_cm, crs.e_cm) for pair in ("constructed", "independent")}
        batch.append(entry)
    doc = {"label": "exploratory", "schema": "expchoice.nav2_batch/v1", "robot": "compact_diff",
           "supersedes": "batch_v0.json (never run)", "footprints": FOOTPRINTS, "surrogate_truth": TRUTH,
           "tie_threshold_s": TIE_S, "sources": R.source_hashes(), "courses": batch}
    with open(os.path.join(HERE, "batch_v1.json"), "w", encoding="utf-8") as f:
        json.dump(doc, f, indent=1, sort_keys=True)
    lines = ["<!-- generated by select_batch_v1.py; exploratory -->",
             "| # | course | from | d (m) | e (m) | d/2rho catalog / Nav2 / physical | physical-body certificate | constructed pair | independent pair |",
             "|---|---|---|---|---|---|---|---|---|"]
    for i, b in enumerate(batch, 1):
        fp = b["footprints"]
        phys = fp["physical"]
        cert = phys["certificate"] + (" (tight, %s four-flow cycles)" % phys["four_flow_cycles"]
                                      if phys["regime"] == "tight" else " (roomy)")
        say = lambda s: "%s (A %s, B %s, gap %+.1f s; cell %.2f, %.2f)" % (  # noqa: E731
            s["winner"] if s["winner"] in ("both fail", "tie") else s["winner"] + " wins", s["success_A"],
            s["success_B"], s["mean_gap_s"], s["cell_d_cm"] / 100, s["cell_e_cm"] / 100)
        lines.append("| %d | `%s`%s | %s | %.2f | %.2f | %s | %s | %s | %s |" % (
            i, b["course_id"], " canary" if b["canary"] else "", b["origin"], b["d_m"], b["e_m"],
            " / ".join("%.3f" % fp[n]["d_over_2rho"] for n in ("catalog", "nav2", "physical")), cert,
            say(b["surrogate"]["constructed"]), say(b["surrogate"]["independent"])))
    text = "\n".join(lines) + "\n"
    with open(os.path.join(HERE, "batch_v1.md"), "w", encoding="utf-8") as f:
        f.write(text)
    print(text)
    assert all(b["in_admissible_box_v0"] for b in batch)


if __name__ == "__main__":
    main()
