#!/usr/bin/env bash
# Regenerate a robot's expanded URDF from the nav xacro (the source of truth) with real xacro
# in the roboboat_dev container, then let UrdfSync bring the prefab to it.
#
# Usage: regen_urdf.sh XACRO [OUT]
#   XACRO  e.g. <mhseals_nav checkout>/description/blastoise/blastoise.xacro
#   OUT    [Assets/Robot Descriptions/<robot>/<robot>.urdf]
# Env: CRANE_URDF_CONTAINER [roboboat_dev]
#
# $(find mhseals_nav) resolves to the given checkout (a throwaway ament prefix), not the
# container's install. One local override: the T200 thruster/propeller meshes get scale 1
# (the crane STLs are in metres; the xacro scales the nav ones by 0.001). The header names the
# xacro and its commit. Afterwards: Crane > URDF > Sync Selected URDF, or the UrdfSync batch.
set -euo pipefail
xacro=$(realpath "${1:?usage: regen_urdf.sh XACRO [OUT]}")
robot=$(basename "$xacro" .xacro)
here=$(cd "$(dirname "$0")/../.." && pwd)
out=${2:-"$here/Assets/Robot Descriptions/$robot/$robot.urdf"}
nav=$(git -C "$(dirname "$xacro")" rev-parse --show-toplevel)
sha=$(git -C "$nav" rev-parse HEAD)
if git -C "$nav" status --porcelain -- description | grep -q .; then sha="$sha+dirty"; fi
rel=${xacro#"$nav"/}
C=${CRANE_URDF_CONTAINER:-roboboat_dev}
docker start "$C" >/dev/null
tmp=/tmp/crane-regen-$$
expanded=$(mktemp)
trap 'rm -f "$expanded"' EXIT
tar -C "$nav" -cf - description | docker exec -i "$C" bash -c "
  mkdir -p $tmp/share/mhseals_nav $tmp/share/ament_index/resource_index/packages
  tar -C $tmp/share/mhseals_nav -xf - && touch $tmp/share/ament_index/resource_index/packages/mhseals_nav"
docker exec "$C" bash -c "source /opt/ros/jazzy/setup.bash
  export AMENT_PREFIX_PATH=$tmp:\$AMENT_PREFIX_PATH
  xacro $tmp/share/mhseals_nav/$rel; rc=\$?; rm -rf $tmp; exit \$rc" > "$expanded"
python3 - "$expanded" "$out" "$rel" "$sha" <<'PY'
import re, sys
src, out, rel, sha = sys.argv[1:]
text = open(src).read()
text, n = re.subn(r'(<mesh filename="[^"]*_(?:thruster|propeller)\.stl") scale="0\.001 0\.001 0\.001"',
                  r'\1 scale="1 1 1"', text)
header = (f'<!-- Generated by Tools/Urdf/regen_urdf.sh from mhseals_nav {rel} at {sha} (xacro, ROS jazzy).\n'
          '     Do not edit: change the xacro, regenerate, then sync the prefab (Crane > URDF, or the UrdfSync batch).\n'
          '     One local difference: the T200 thruster/propeller meshes use scale 1 (the STLs are in metres; the xacro scales them by 0.001).\n'
          "     A player places its sensors from the stack's own expansion (--crane-urdf); this file is the editor default. -->\n")
text = re.sub(r'(autogenerated by xacro from )/tmp/crane-regen-\d+/share/mhseals_nav/', r'\1', text)
text, h = re.subn(r'^(<\?xml[^>]*\?>\n)', lambda m: m.group(1) + header, text, count=1)
if not h:
    sys.exit('regen_urdf: xacro output has no XML declaration')
open(out, 'w').write(text)
print(f'wrote {out} ({rel} at {sha}; {n} T200 meshes at scale 1)')
PY
