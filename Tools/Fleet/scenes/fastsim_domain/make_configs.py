"""Write one fastsim domain YAML per (family, split, plan) under configs/ from the template below.

    python3 make_configs.py          # rewrites configs/*.yaml
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from scenes.families import generate, GENERATORS  # noqa: E402

TEMPLATE = """# fastsim fleet domain: family {family}, split {split}, plan {plan} (generated by make_configs.py)
adapter: {{ref: ../fleet_domain.py:FleetAdapter, options: {{gain: 2.0}}}}
scenarios:
  dir: ../scenarios
  pattern: '{{family}}-{{split}}-{{plan}}-s{{seed}}.json'
  fields: {{family: {family}, split: {split}, plan: {plan}}}
  generate: ['{{python}}', '{{base}}/../gen_scenarios.py', --family, '{{family}}', --split, '{{split}}', --plan,
             '{{plan}}', --from, '{{seeds_from}}', --to, '{{seeds_to}}', --dir, '{{dir}}']
  format: {{ref: ../fleet_domain.py:FleetBundleFormat}}
vehicle: {{ref: ../fleet_domain.py:FleetPlant, gain: 2.0}}
perception: {{name: cone, hfov_deg: 70.0, range_m: 4.0, occlusion: true, mount: [0.2, 0.0, 0.0]}}
time_limit_s: 600
workers: 1
"""


def main():
    out = Path(__file__).parent / "configs"
    out.mkdir(exist_ok=True)
    for f in GENERATORS:
        for split in ("train", "heldout"):
            _, task = generate(f, 1, split)
            for plan in task["plans"]:
                p = out / ("%s-%s-%s.yaml" % (f, split, plan))
                p.write_text(TEMPLATE.format(family=f, split=split, plan=plan))
                print(p.name)


if __name__ == "__main__":
    main()
